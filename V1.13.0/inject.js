// Script Enjekte Etme Yardımcısı
function injectScript(src, data = {}) {
  return new Promise((resolve, reject) => {
    const script = document.createElement('script')
    script.src = chrome.runtime.getURL(src)
    script.type = 'text/javascript'

    script.onload = function () {
      resolve()
      this.remove()
    }
    script.onerror = reject
    document.documentElement.appendChild(script)
  })
}

// Sayfadan gelen "FROM_PAGE_CLICK" mesajlarını yakalayıp background.js'e postalar
window.addEventListener('message', (event) => {
  // Mesajın kendi sayfamızdan geldiğinden emin olalım
  if (event.source !== window) return

  if (event.data && event.data.type === 'FROM_PAGE_CLICK') {
    // Sayfadan gelen X ve Y'yi alıp Background'a (Tünel Motoruna) gönder
    chrome.runtime
      .sendMessage({
        x: event.data.x,
        y: event.data.y,
      })
      .catch((err) => console.log("Background'a iletilemedi, bot kapalı olabilir.", err))
  }
})

