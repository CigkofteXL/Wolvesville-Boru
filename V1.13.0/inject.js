window.addEventListener('message', function(event) {
    // Güvenlik: Sadece aynı pencereden gelen mesajları kabul et
    if (event.source !== window) return;

    if (event.data && event.data.type === 'BORU_NUKER_ACTION') {
        const action = event.data.action;
        
        if (action === 'SELF_DESTRUCT' || action === 'DISABLE_EXTENSION') {
            // Mesajı güvenli hattan background.js'e postala
            chrome.runtime.sendMessage({ action: action });
        }
    }
});